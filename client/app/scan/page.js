'use client';

import React, { useState, useEffect, useRef } from 'react';
import Link from 'next/link';
import { useAuth } from '@/context/AuthContext';
import { api } from '@/lib/api';
import {
  KeyRound,
  Search,
  Scale,
  ArrowLeft,
  Check,
  RefreshCw,
  LogOut,
  Building2,
  Gift,
  ShieldCheck,
} from 'lucide-react';
import confetti from 'canvas-confetti';
import { formatHostel, formatLocation } from '@/lib/formatHostel';

export default function ScanQrPage() {
  const { user, logout } = useAuth();

  const [manualCode, setManualCode] = useState('');
  const [lookupLoading, setLookupLoading] = useState(false);
  const [availableItems, setAvailableItems] = useState([]);

  const [scannedItem, setScannedItem] = useState(null);
  const [scannedHandovers, setScannedHandovers] = useState([]);

  const [enteredOtp, setEnteredOtp] = useState('');
  const [actualWeight, setActualWeight] = useState('');
  const [collectionLocation, setCollectionLocation] = useState('Campus Collection Hub');
  const [notes, setNotes] = useState('Weighed on digital scale & 4-digit OTP verified by collection squad');
  const [submitLoading, setSubmitLoading] = useState(false);
  const [submitSuccess, setSubmitSuccess] = useState(false);
  const [awardedPoints, setAwardedPoints] = useState(0);
  const [generatedCoupon, setGeneratedCoupon] = useState(null);
  const [error, setError] = useState('');

  useEffect(() => {
    api
      .getItems()
      .then((res) => {
        if (res.success && res.items) {
          // Filter to items that are submitted/pending collection
          setAvailableItems(res.items.filter((i) => i.status === 'submitted' || i.status === 'registered'));
        }
      })
      .catch((e) => console.warn('Could not fetch items:', e));
  }, []);

  const handleLookup = async (code) => {
    setLookupLoading(true);
    setError('');

    try {
      const res = await api.scanLookup(code);
      if (res.success && res.item) {
        setScannedItem(res.item);
        setScannedHandovers(res.handovers || []);
        setActualWeight(res.item.actualWeight || res.item.approxWeight || '1.0');
        if (res.item.location) {
          setCollectionLocation(res.item.location);
        }
      } else {
        setError(res.message || 'Tracking ID not found in campus ledger.');
      }
    } catch (err) {
      setError(err.message || 'Lookup failed.');
    } finally {
      setLookupLoading(false);
    }
  };

  const handleManualLookup = (e) => {
    e.preventDefault();
    if (manualCode.trim()) {
      handleLookup(manualCode.trim());
    }
  };

  const handleMarkCollected = async (e) => {
    e.preventDefault();
    if (!scannedItem) return;

    if (!enteredOtp || enteredOtp.trim().length !== 4) {
      setError('Enter the 4-digit Handover OTP generated by the submitter.');
      return;
    }

    const weightNum = parseFloat(actualWeight);
    if (isNaN(weightNum) || weightNum <= 0) {
      setError('Enter a calibrated positive mass in kg.');
      return;
    }

    setSubmitLoading(true);
    setError('');

    try {
      const res = await api.collectItem(scannedItem._id || scannedItem.id, {
        actualWeight: weightNum,
        location: collectionLocation,
        notes,
        otp: enteredOtp.trim(),
      });

      if (res.success) {
        setSubmitSuccess(true);
        setAwardedPoints(res.pointsAwarded || Math.round(weightNum * 10));
        setGeneratedCoupon(res.coupon || null);
        confetti({ particleCount: 40, spread: 50 });
      } else {
        setError(res.message || 'Failed to record collection in database.');
      }
    } catch (err) {
      setError(err.message || 'Error executing collection handshake.');
    } finally {
      setSubmitLoading(false);
    }
  };

  const resetScanner = () => {
    setScannedItem(null);
    setScannedHandovers([]);
    setSubmitSuccess(false);
    setActualWeight('');
    setEnteredOtp('');
    setGeneratedCoupon(null);
    setError('');
  };

  const calculatedPoints = Math.round((parseFloat(actualWeight) || 0) * 10);

  return (
    <div className="min-h-screen bg-[#000000] text-[#f0f0fa] flex flex-col font-sans">
      {/* Top Telemetry Strip */}
      <div className="bg-[#000000] border-b border-[#3a3a3f] px-6 py-2 text-xs">
        <div className="max-w-7xl mx-auto flex items-center justify-between">
          <div className="flex items-center gap-3">
            <span className="w-1.5 h-1.5 rounded-full bg-[#ffffff] inline-block animate-pulse" />
            <span className="spacex-caption">// COLLECTION SQUAD OPERATOR:</span>
            <span className="font-mono text-xs text-[#ffffff]">
              {user?.name || 'CAMPUS COLLECTION TEAM'} [{user?.role?.toUpperCase() || 'COLLECTOR'}]
            </span>
          </div>

          <button
            onClick={logout}
            className="text-[#5a5a5f] hover:text-[#ffffff] text-[11px] font-bold uppercase tracking-[1.17px] transition-colors cursor-pointer bg-transparent border-0"
          >
            Sign Out
          </button>
        </div>
      </div>

      {/* Command Bar */}
      <header className="border-b border-[#3a3a3f] px-6 py-4 bg-[#000000]">
        <div className="max-w-7xl mx-auto flex items-center justify-between">
          <div className="flex items-center gap-3">
            <span className="font-['D-DIN-Bold'] text-2xl tracking-[3px] text-[#ffffff] uppercase">
              ECOLOOP
            </span>
            <span className="text-[#3a3a3f]">/</span>
            <span className="spacex-caption">4-DIGIT OTP VERIFICATION INTAKE</span>
          </div>

          <button
            onClick={() => (window.history.length > 1 ? window.history.back() : (window.location.href = '/'))}
            className="btn-spacex"
          >
            <ArrowLeft className="w-3.5 h-3.5" />
            <span>Back</span>
          </button>
        </div>
      </header>

      {/* Main Section */}
      <main className="max-w-4xl mx-auto px-6 py-12 w-full flex-1">
        {/* Banner */}
        <div className="border-b border-[#3a3a3f] pb-8 mb-8 flex flex-col md:flex-row md:items-end justify-between gap-6">
          <div>
            <div className="spacex-caption mb-2">// 4-DIGIT SECURITY OTP CUSTODY PROTOCOL</div>
            <h1 className="font-['D-DIN-Bold'] text-3xl sm:text-5xl font-black text-[#ffffff] uppercase tracking-tight">
              COLLECTION HANDOVER &amp; WEIGHING
            </h1>
            <p className="text-[#8a8a93] text-sm mt-2 max-w-lg">
              Collect e-waste from students, <span className="text-[#ffffff] font-mono">cse.hod@nmamit.campus</span>, or college departments. Enter the submitter&apos;s 4-digit OTP to verify custody, calibrate mass, and issue instant food coupons.
            </p>
          </div>

          <div className="border border-[#3a3a3f] p-4 bg-[#0a0a0a] shrink-0 text-right">
            <div className="spacex-caption">DESTINATION</div>
            <div className="font-['D-DIN-Bold'] text-lg text-[#ffffff] mt-1">AUTHORISED RECYCLER</div>
            <div className="text-[10px] text-[#22c55e] font-mono mt-0.5">MoEFCC / CPCB Partner</div>
          </div>
        </div>

        {error && (
          <div className="mb-8 p-4 border border-red-500/50 bg-red-950/20 text-xs font-mono text-red-200">
            // ERROR: {error}
          </div>
        )}

        {!scannedItem ? (
          <div className="border border-[#3a3a3f] bg-[#0a0a0a] p-8 space-y-6">
            <div className="max-w-xl mx-auto space-y-6">
              <form onSubmit={handleManualLookup} className="space-y-3">
                <label className="block spacex-caption">ENTER TRACKING CODE OR HARDWARE ID</label>
                <div className="flex gap-3">
                  <input
                    type="text"
                    value={manualCode}
                    onChange={(e) => setManualCode(e.target.value)}
                    placeholder="ECO-2026-XXXX"
                    className="flex-1 px-4 py-3 font-mono text-sm uppercase bg-[#000000] border border-[#3a3a3f] text-[#ffffff] focus:outline-none focus:border-[#ffffff]"
                  />
                  <button
                    type="submit"
                    disabled={!manualCode.trim() || lookupLoading}
                    className="btn-spacex"
                  >
                    <Search className="w-4 h-4" />
                    <span>{lookupLoading ? 'Locating...' : 'Lookup Unit'}</span>
                  </button>
                </div>
              </form>

              {availableItems.length > 0 && (
                <div className="border-t border-[#3a3a3f] pt-6">
                  <div className="spacex-caption mb-3">// PENDING CAMPUS SUBMISSIONS AWAITING OTP VERIFICATION:</div>
                  <div className="space-y-2.5 max-h-72 overflow-y-auto pr-1">
                    {availableItems.map((item) => (
                      <div
                        key={item._id || item.trackingCode}
                        onClick={() => handleLookup(item.trackingCode)}
                        className="p-3.5 border border-[#3a3a3f] hover:border-[#ffffff] bg-[#000000] flex justify-between items-center cursor-pointer transition-colors"
                      >
                        <div>
                          <div className="flex items-center gap-2">
                            <span className="font-mono text-xs font-bold text-[#ffffff]">{item.trackingCode}</span>
                            <span className="text-[10px] px-1.5 py-0.5 bg-[#ffffff]/10 text-[#ffffff] font-mono uppercase">
                              {item.userBranch || 'Campus'}
                            </span>
                          </div>
                          <div className="text-xs text-[#8a8a93] mt-1">
                            {item.userName} • {item.type} ({item.approxWeight || '1'} kg)
                          </div>
                        </div>

                        <div className="text-right">
                          <span className="text-[11px] font-mono px-2 py-1 border border-amber-500/40 text-amber-300 bg-amber-500/10">
                            AWAITING OTP
                          </span>
                        </div>
                      </div>
                    ))}
                  </div>
                </div>
              )}
            </div>
          </div>
        ) : submitSuccess ? (
          <div className="border border-[#3a3a3f] bg-[#0a0a0a] p-10 text-center space-y-6">
            <div className="inline-flex p-3 bg-emerald-500/10 border border-emerald-500/40 rounded-full text-emerald-400">
              <Check className="w-8 h-8" />
            </div>

            <div className="spacex-caption text-emerald-400">// STATUS: 4-DIGIT OTP VERIFIED &amp; CUSTODY TRANSFERRED</div>
            <h2 className="font-['D-DIN-Bold'] text-3xl sm:text-4xl text-[#ffffff] uppercase">
              PHYSICAL HANDOVER COMPLETE
            </h2>
            <p className="text-[#8a8a93] text-sm max-w-md mx-auto">
              Hardware marked as collected. Transferred to Authorised Recycler pipeline. Submitter awarded {awardedPoints} green credits.
            </p>

            {generatedCoupon && (
              <div className="max-w-md mx-auto p-4 border border-amber-500/50 bg-[#161205] text-left space-y-2">
                <div className="flex items-center gap-2 text-amber-400 font-['D-DIN-Bold'] text-sm uppercase">
                  <Gift className="w-4 h-4" />
                  <span>Instant Campus Cafeteria Coupon Issued</span>
                </div>
                <div className="font-mono text-lg font-bold text-amber-300">
                  {generatedCoupon.code}
                </div>
                <div className="text-xs text-[#a0a0a8]">
                  {generatedCoupon.item} • {generatedCoupon.vendor} (Expires: {generatedCoupon.validUntil})
                </div>
              </div>
            )}

            <div className="flex justify-center gap-4 pt-4">
              <button onClick={resetScanner} className="btn-spacex">
                <RefreshCw className="w-3.5 h-3.5" />
                <span>Verify Next Unit</span>
              </button>
              <Link href="/" className="btn-spacex-muted btn-spacex">
                <span>Return to Overview</span>
              </Link>
            </div>
          </div>
        ) : (
          /* DETAILS & 4-DIGIT OTP & WEIGHT INPUT */
          <div className="border border-[#3a3a3f] bg-[#0a0a0a] p-8 space-y-8">
            <div className="border-b border-[#3a3a3f] pb-6 flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4">
              <div>
                <div className="spacex-caption mb-1">// HARDWARE INTAKE RECORD</div>
                <h3 className="font-['D-DIN-Bold'] text-2xl text-[#ffffff] uppercase">
                  {scannedItem.type}
                </h3>
                <div className="font-mono text-xs text-[#8a8a93] mt-1">{scannedItem.trackingCode}</div>
              </div>

              <div className="text-right">
                <span className="inline-block px-3 py-1 bg-amber-500/10 border border-amber-500/40 text-amber-300 font-mono text-xs uppercase">
                  OTP VERIFICATION REQUIRED
                </span>
              </div>
            </div>

            <div className="grid grid-cols-2 md:grid-cols-4 gap-4 text-xs border-b border-[#3a3a3f] pb-6">
              <div>
                <span className="spacex-caption">SUBMITTER:</span>
                <div className="font-semibold text-[#ffffff] mt-1 truncate">{scannedItem.userName}</div>
                <div className="text-[10px] text-[#8a8a93] font-mono truncate">{scannedItem.userEmail}</div>
              </div>
              <div>
                <span className="spacex-caption">BRANCH / DEPT:</span>
                <div className="font-semibold text-[#ffffff] mt-1">{scannedItem.userBranch || 'CSE / Dept'}</div>
              </div>
              <div>
                <span className="spacex-caption">PICKUP LOCATION:</span>
                <div className="font-semibold text-[#ffffff] mt-1 truncate">{formatLocation(scannedItem.location, scannedItem.userHostel)}</div>
              </div>
              <div>
                <span className="spacex-caption">ESTIMATED MASS:</span>
                <div className="font-mono text-[#ffffff] mt-1">{scannedItem.approxWeight} KG</div>
              </div>
            </div>

            <form onSubmit={handleMarkCollected} className="space-y-6">
              {/* 4-Digit Handover OTP Input */}
              <div className="border-2 border-emerald-500/40 bg-emerald-950/10 p-5 rounded-sm">
                <label className="flex items-center gap-2 font-['D-DIN-Bold'] text-sm text-emerald-400 uppercase tracking-wider mb-2">
                  <KeyRound className="w-4 h-4" />
                  <span>Enter 4-Digit Handover OTP from Submitter *</span>
                </label>
                <p className="text-xs text-[#8a8a93] mb-3">
                  Ask the student or department head (e.g. cse.hod@nmamit.campus) for their 4-digit code shown on their dashboard.
                </p>
                <input
                  type="text"
                  maxLength={4}
                  required
                  value={enteredOtp}
                  onChange={(e) => setEnteredOtp(e.target.value.replace(/\D/g, ''))}
                  placeholder="• • • •"
                  className="w-full sm:w-64 px-4 py-3 bg-[#000000] border-2 border-emerald-500/60 font-mono text-2xl tracking-[12px] text-center text-emerald-400 placeholder-[#3a3a3f] focus:outline-none focus:border-emerald-400"
                />
              </div>

              <div>
                <label className="block spacex-caption mb-2">CALIBRATED DIGITAL MASS (KG) *</label>
                <div className="relative">
                  <input
                    type="number"
                    step="0.05"
                    min="0.05"
                    required
                    value={actualWeight}
                    onChange={(e) => setActualWeight(e.target.value)}
                    placeholder="2.5"
                    className="w-full px-4 py-3 font-mono text-xl bg-[#000000] border border-[#3a3a3f] text-[#ffffff] focus:outline-none focus:border-[#ffffff]"
                  />
                </div>
              </div>

              <div className="border border-[#3a3a3f] p-4 bg-[#000000] flex justify-between items-center text-xs">
                <span className="spacex-caption">CALCULATED GREEN CREDITS:</span>
                <span className="font-['D-DIN-Bold'] text-xl text-[#22c55e]">+{calculatedPoints} PTS</span>
              </div>

              <div>
                <label className="block spacex-caption mb-2">COLLECTION HUB / RECEPTION BAY</label>
                <input
                  type="text"
                  required
                  value={collectionLocation}
                  onChange={(e) => setCollectionLocation(e.target.value)}
                  className="w-full px-4 py-3 text-sm bg-[#000000] border border-[#3a3a3f] text-[#ffffff] focus:outline-none focus:border-[#ffffff]"
                />
              </div>

              <div className="pt-4 border-t border-[#3a3a3f] flex items-center justify-between">
                <button
                  type="button"
                  onClick={resetScanner}
                  className="btn-spacex-muted btn-spacex"
                >
                  Cancel
                </button>

                <button
                  type="submit"
                  disabled={submitLoading || enteredOtp.length !== 4 || parseFloat(actualWeight) <= 0}
                  className="btn-spacex px-8 py-3 bg-[#ffffff] text-[#000000] hover:bg-[#e0e0e0] font-bold"
                >
                  <ShieldCheck className="w-4 h-4 mr-2" />
                  {submitLoading ? 'VERIFYING...' : 'VERIFY OTP & RECORD COLLECTION'}
                </button>
              </div>
            </form>
          </div>
        )}
      </main>
    </div>
  );
}
